#!/usr/bin/env python3
"""axi0 picks register -> the app's list and the human register.

    python3 tools/picks.py           write app/.../model/Picks.kt and PICKS.md from docs/picks.json
    python3 tools/picks.py --check   change nothing; exit 1 when either file is out of date (CI runs this)

docs/picks.json is the source of truth: one free and open-source app for each everyday Google app, with the
package id, the licence and the anti-features exactly as the repository's index states them on the day we checked.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs', 'picks.json')
KT = os.path.join(ROOT, 'app/src/main/kotlin/com/looker/droidify/model/Picks.kt')
MD = os.path.join(ROOT, 'PICKS.md')


def render():
    reg = json.load(open(SRC, encoding='utf-8'))
    picks = reg['picks']
    kt = ['// Generated by tools/picks.py from docs/picks.json. Edit the JSON, then run the script.',
          'package com.looker.droidify.model', '',
          '/** axi0 picks: one free and open-source app for each everyday Google app (register: PICKS.md). */',
          'object Picks {', '    val packageNames: List<String> = listOf(']
    kt += [f'        "{p["package"]}", // instead of {p["instead_of"]}: {p["name"]}, {p["license"]}' for p in picks]
    kt += ['    )', '}', '']
    md = ['# axi0 picks', '',
          'One free and open-source app for each everyday Google app. F0Store shows them as the "axi0 picks" shelf, the',
          'first thing on the Explore tab. Every pick comes from a repository F0Store ships with and is shown with its',
          'own licence and with the anti-features its repository marks, exactly as they are marked there.', '',
          f'Checked on {reg["checked"]} against the F-Droid index (index-v2.json, SHA-256 `{reg["index_sha256"]}`).',
          'Generated by `tools/picks.py` from `docs/picks.json`.', '',
          '| Instead of | Pick | What it does | Package | Licence | Anti-features | Repository |',
          '|---|---|---|---|---|---|---|']
    md += [f'| {p["instead_of"]} | [{p["name"]}]({p["source"]}) | {p["role"]} | `{p["package"]}` | {p["license"]} | '
           f'{", ".join(p["antiFeatures"]) or "none"} | {p["repo"]} |' for p in picks]
    md += ['', 'Rules for a pick: free and open-source (an OSI- or FSF-approved licence), in a repository F0Store ships with,',
           'maintained, and the plainest app that does the job. Never an app copied from Google Play.', '']
    return '\n'.join(kt), '\n'.join(md)


def main():
    kt, md = render()
    stale = [p for p, body in ((KT, kt), (MD, md)) if not os.path.exists(p) or open(p, encoding='utf-8').read() != body]
    if '--check' in sys.argv:
        if stale:
            sys.exit('out of date: ' + ', '.join(os.path.relpath(p, ROOT) for p in stale) + ' (run tools/picks.py)')
        print('picks: up to date')
        return
    for p, body in ((KT, kt), (MD, md)):
        open(p, 'w', encoding='utf-8').write(body)
    print(f'picks: wrote {len(json.load(open(SRC))["picks"])} picks')


if __name__ == '__main__':
    main()
